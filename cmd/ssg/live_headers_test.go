// TestTheHeaderTableSwapIsAtomic: a request sees one whole table or the other.
func TestTheHeaderTableSwapIsAtomic(t *testing.T) {
	resetLiveRules(t)
	h := liveHeadersHandler(staticSaying("static"))
	first := parseHeadersFile("/*\n  X-Table: a\n", func(string, ...any) {})
	liveHeaders.Store(&first)

	done := make(chan struct{})
	go func() {
		defer close(done)
		for i := 0; i < 200; i++ {
			value := "a"
			if i%2 == 0 {
				value = "b"
			}
			table := parseHeadersFile("/*\n  X-Table: "+value+"\n", func(string, ...any) {})
			liveHeaders.Store(&table)
		}
	}()
	for i := 0; i < 200; i++ {
		if got := getPath(h, "/x").Header().Get("X-Table"); got != "a" && got != "b" {
			t.Fatalf("X-Table = %q during a swap", got)
		}
	}
	<-done
}

// TestBothTablesAreRepublishedTogether: the two files change on every build, so
// one entry point re-reads both.
func TestBothTablesAreRepublishedTogether(t *testing.T) {
	resetLiveRules(t)
	dir := t.TempDir()
	write := func(name, body string) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("_redirects", "/old /new 301\n")
	write("_headers", "/*\n  X-Build: one\n")

	cfg := config.DefaultConfig()
	cfg.Quiet = true
	cfg.OutputDir = dir
	republishOutputRules(cfg)

	redirects := liveRedirectHandler(staticSaying("static"))
	headers := liveHeadersHandler(staticSaying("static"))
	if got := getPath(redirects, "/old").Header().Get("Location"); got != "/new" {
		t.Errorf("Location = %q", got)
	}
	if got := getPath(headers, "/x").Header().Get("X-Build"); got != "one" {
		t.Errorf("X-Build = %q", got)
	}

	// A rebuild rewrites both; the next request must see the new pair.
	write("_redirects", "/old /newer 301\n")
	write("_headers", "/*\n  X-Build: two\n")
	republishOutputRules(cfg)
	if got := getPath(redirects, "/old").Header().Get("Location"); got != "/newer" {
		t.Errorf("after the rebuild Location = %q", got)
	}
	if got := getPath(headers, "/x").Header().Get("X-Build"); got != "two" {
		t.Errorf("after the rebuild X-Build = %q", got)
	}
}

// TestTheServerChainOrdersEndpointsRedirectsHeadersStatic pins the order the
// whole feature rests on, through the handler the server actually builds.
func TestTheServerChainOrdersEndpointsRedirectsHeadersStatic(t *testing.T) {
	resetLiveRules(t)
	resetLiveEndpoints(t)
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "index.html"), []byte("<html></html>"), 0o600); err != nil {
		t.Fatal(err)
	}
	for name, body := range map[string]string{
		"_redirects": "/gone-away/ /moved/ 301\n",
		"_headers":   "/*\n  X-From-File: yes\n",
	} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}

	cfg := config.DefaultConfig()
	cfg.Quiet = true
	cfg.OutputDir = dir
	cfg.Endpoints = []config.Endpoint{{Path: "/api/ping", Type: "redirect", To: "/pong/"}}
	h := buildServerHandler(cfg, false)

	// An endpoint answers before any file rule.
	if got := getPath(h, "/api/ping").Header().Get("Location"); got != "/pong/" {
		t.Errorf("endpoint Location = %q", got)
	}
	// A file redirect answers before the static tree.
	if got := getPath(h, "/gone-away/").Header().Get("Location"); got != "/moved/" {
		t.Errorf("redirect Location = %q", got)
	}
	// And a served asset carries the file's headers.
	rec := httptest.NewRecorder()
	h.ServeHTTP(rec, httptest.NewRequest(http.MethodGet, "/", nil))
	if got := rec.Header().Get("X-From-File"); got != "yes" {
		t.Errorf("X-From-File = %q on the served page", got)
	}
}

// TestAPatternWithSeveralWildcardsMatches: `headers:` takes any pattern the
// operator writes, not only the shapes the defaults use, so the matcher has to
// cope with a wildcard that is neither first nor last.
func TestAPatternWithSeveralWildcardsMatches(t *testing.T) {
	resetLiveRules(t)
	h, _ := publishHeaderText(t, "/assets/*/dist/*.js\n  X-Bundle: yes\n")

	if got := getPath(h, "/assets/app/dist/main.js").Header().Get("X-Bundle"); got != "yes" {
		t.Errorf("X-Bundle = %q, want the block to apply", got)
	}
	// The middle literal has to be there, and the suffix has to match.
	for _, miss := range []string{"/assets/app/build/main.js", "/assets/app/dist/main.css", "/other/app/dist/main.js"} {
		if got := getPath(h, miss).Header().Get("X-Bundle"); got != "" {
			t.Errorf("%s picked the block up: %q", miss, got)
		}
	}
}
