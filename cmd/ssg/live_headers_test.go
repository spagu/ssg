// publishHeaderText parses text and mounts the handler over a stand-in server.
func publishHeaderText(t *testing.T, text string) (http.Handler, []string) {
	t.Helper()
	var warnings []string
	table := parseHeadersFile(text, quietWarn(&warnings))
	liveHeaders.Store(&table)
	return liveHeadersHandler(staticSaying("static")), warnings
}

// defaultHeadersFile is what the generator writes with no `headers:` config —
// the shape the matcher actually has to cope with, not an invented one.
const defaultHeadersFile = `# Cloudflare Pages Headers
# Generated by SSG

# Security headers for all pages
/*
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin

# Cache static assets for 1 year
/css/*
  Cache-Control: public, max-age=31536000, immutable

# Cache HTML pages for 1 hour
/*.html
  Cache-Control: public, max-age=3600
/
  Cache-Control: public, max-age=3600
`

// TestAPatternAddsItsHeaders: the plain case, on the file the build writes.
func TestAPatternAddsItsHeaders(t *testing.T) {
	resetLiveRules(t)
	h, warnings := publishHeaderText(t, defaultHeadersFile)
	if len(warnings) != 0 {
		t.Fatalf("the generator's own format must parse cleanly: %v", warnings)
	}

	rec := getPath(h, "/css/site.css")
	if got := rec.Header().Get("Cache-Control"); got != "public, max-age=31536000, immutable" {
		t.Errorf("Cache-Control = %q", got)
	}
	if got := rec.Header().Get("X-Content-Type-Options"); got != "nosniff" {
		t.Errorf("the /* block must apply too: %q", got)
	}
}

// TestASuffixGlobMatches: `/*.html` is a wildcard in the middle of a pattern,
// which a naive prefix matcher gets wrong.
func TestASuffixGlobMatches(t *testing.T) {
	resetLiveRules(t)
	h, _ := publishHeaderText(t, defaultHeadersFile)

	if got := getPath(h, "/about.html").Header().Get("Cache-Control"); got != "public, max-age=3600" {
		t.Errorf("/about.html Cache-Control = %q", got)
	}
	// A directory URL is not an .html path and must not pick that block up.
	if got := getPath(h, "/about/").Header().Get("Cache-Control"); got != "" {
		t.Errorf("/about/ Cache-Control = %q, want none from the file", got)
	}
	// The bare `/` block is exact, so it applies to the root and nowhere else.
	if got := getPath(h, "/").Header().Get("Cache-Control"); got != "public, max-age=3600" {
		t.Errorf("root Cache-Control = %q", got)
	}
}

// TestTheFirstMatchingValueWins: Cloudflare applies the first matching value per
// header name, which is why block order in the generated file is deliberate.
func TestTheFirstMatchingValueWins(t *testing.T) {
	resetLiveRules(t)
	h, _ := publishHeaderText(t, "/css/*\n  Cache-Control: first\n/*\n  Cache-Control: second\n")
	if got := getPath(h, "/css/a.css").Header().Get("Cache-Control"); got != "first" {
		t.Errorf("Cache-Control = %q, want the earlier block's value", got)
	}
}

// TestTheFileWinsOverTheBuiltInSecurityHeaders: what the deployed platform
// would serve is the whole point of a preview that reads this file.
func TestTheFileWinsOverTheBuiltInSecurityHeaders(t *testing.T) {
	resetLiveRules(t)
	table := parseHeadersFile("/*\n  X-Frame-Options: DENY\n", func(string, ...any) {})
	liveHeaders.Store(&table)

	// The real chain: the middleware sets SAMEORIGIN, the file then says DENY.
	h := securityHeadersMiddleware(liveHeadersHandler(staticSaying("static")), false)
	rec := getPath(h, "/anything")
	if got := rec.Header().Get("X-Frame-Options"); got != "DENY" {
		t.Errorf("X-Frame-Options = %q, want the file's value", got)
	}
	// A header the file does not mention keeps the built-in value.
	if got := rec.Header().Get("X-Content-Type-Options"); got != "nosniff" {
		t.Errorf("X-Content-Type-Options = %q", got)
	}
}

// TestANonMatchingPathIsUntouched: nothing is added where nothing matches.
func TestANonMatchingPathIsUntouched(t *testing.T) {
	resetLiveRules(t)
	h, _ := publishHeaderText(t, "/css/*\n  Cache-Control: cached\n")
	rec := getPath(h, "/index.html")
	if got := rec.Header().Get("Cache-Control"); got != "" {
		t.Errorf("Cache-Control = %q, want none", got)
	}
	if rec.Body.String() != "static" {
		t.Errorf("the response must still be served: %q", rec.Body)
	}
}

// TestAMalformedHeaderLineIsSkipped: a file the build wrote must never take the
// server down, and a warning must name the line so it can be found.
func TestAMalformedHeaderLineIsSkipped(t *testing.T) {
	resetLiveRules(t)
	h, warnings := publishHeaderText(t, strings.Join([]string{
		"  Orphan: before any pattern",
		"/*",
		"  no-colon-here",
		"  : empty name",
		"  X-Kept: yes",
	}, "\n"))

	if len(warnings) != 3 {
		t.Fatalf("want three warnings, got %d: %v", len(warnings), warnings)
	}
	for _, w := range warnings {
		if !strings.Contains(w, "_headers:") {
			t.Errorf("a warning must name the line: %q", w)
		}
	}
	if got := getPath(h, "/x").Header().Get("X-Kept"); got != "yes" {
		t.Errorf("the good line must survive: %q", got)
	}
}

